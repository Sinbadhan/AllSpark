    lang = get_language()
    msg = MESSAGES.get(lang, MESSAGES[DEFAULT_LANGUAGE]).get(key, key)
    if kwargs:
        try:
            return msg.format(**kwargs)
        except (KeyError, IndexError):
            return msg
    return msg
